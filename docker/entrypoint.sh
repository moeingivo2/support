#!/bin/sh
# مالکیت مسیرهای نوشتنی قبل از exec.
#
# پروسه‌های php-fpm با کاربر www-data اجرا می‌شوند، اما اگر ولوم
# storage-data پیش‌تر با مالک root ساخته شده باشد (یا از یک میزبان/بکاپ
# دیگر بیاید) هیچ آپلودی نوشته نمی‌شود و تنها خطای گمراه‌کننده‌ی
# «ذخیره فایل روی سرور ناموفق بود» دیده می‌شود.
#
# این کار هر بار در شروع کانتینر انجام می‌شود و روی مسیر mount‌شده بی‌اثر
# نیست چون تنها مالکیت را هم‌تراز می‌کند.
set -e

chown -R www-data:www-data /var/www/storage /var/www/bootstrap/cache 2>/dev/null || true

exec "$@"
